export function getCategoryShapeSvg(shape, size = 14, color = 'currentColor', strokeColor = '#ffffff') {
  const s = (shape || '').toLowerCase();
  switch (s) {
    case 'square':
      return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" class="cat-shape-svg cat-shape-square"><rect x="2" y="2" width="12" height="12" rx="2" fill="${color}" stroke="${strokeColor}" stroke-width="1.5"/></svg>`;
    case 'triangle':
      return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" class="cat-shape-svg cat-shape-triangle"><polygon points="8,1.5 15,14 1,14" fill="${color}" stroke="${strokeColor}" stroke-width="1.5" stroke-linejoin="round"/></svg>`;
    case 'star':
      return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" class="cat-shape-svg cat-shape-star"><polygon points="8,1 10.2,5.5 15,6.2 11.5,9.6 12.3,14.5 8,12.2 3.7,14.5 4.5,9.6 1,6.2 5.8,5.5" fill="${color}" stroke="${strokeColor}" stroke-width="1.2" stroke-linejoin="round"/></svg>`;
    case 'diamond':
      return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" class="cat-shape-svg cat-shape-diamond"><polygon points="8,1.5 14.5,8 8,14.5 1.5,8" fill="${color}" stroke="${strokeColor}" stroke-width="1.5" stroke-linejoin="round"/></svg>`;
    case 'hexagon':
      return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" class="cat-shape-svg cat-shape-hexagon"><polygon points="8,1.5 14.5,4.8 14.5,11.2 8,14.5 1.5,11.2 1.5,4.8" fill="${color}" stroke="${strokeColor}" stroke-width="1.5" stroke-linejoin="round"/></svg>`;
    case 'circle':
    default:
      return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" class="cat-shape-svg cat-shape-circle"><circle cx="8" cy="8" r="6" fill="${color}" stroke="${strokeColor}" stroke-width="1.5"/></svg>`;
  }
}

