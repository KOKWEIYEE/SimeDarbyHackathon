export const ALL_CATEGORY_ITEMS = CATEGORY_GROUPS.flatMap((group) =>
  group.items.map((item) => ({
    ...item,
    groupId: group.id,
    groupName: group.name,
    shape: item.shape || group.shape,
    shapeSymbol: item.shapeSymbol || group.shapeSymbol,
    color: item.color,
  }))
);

export const CATEGORIES_BY_ID = new Map(ALL_CATEGORY_ITEMS.map((item) => [item.id, item]));

export function getCategoryMeta(catIdOrItem) {
  if (!catIdOrItem) return null;
  const id = typeof catIdOrItem === 'string' ? catIdOrItem : (catIdOrItem.id || catIdOrItem.categoryId);
  return CATEGORIES_BY_ID.get(id) || null;
}
